/*
*********************************************************************************************************
*
*   文件名称 : bsp_retarget.c
*   说    明 : GCC / newlib 下的 printf 重定向适配层（本模板新增文件）
*
*   背景：安富莱 BSP 在 bsp_uart_fifo.c 里重定义 fputc()，那是 ARMCC + microlib
*         的重定向方式。GCC 使用 newlib，printf 走 _write() -> __io_putchar()，
*         不会调用 fputc()。若不做适配，编译能过但串口没有任何输出。
*
*   做法：syscalls.c（CubeMX 提供）里的 _write 会逐个调用弱符号 __io_putchar，
*         这里给出强实现，把字符交给安富莱串口 FIFO 的 comSendChar(COM1, ...)。
*         原 BSP 的 fputc 保留不动，不影响 GCC 构建。
*
*   注意：需先调用 bsp_Init() 完成串口初始化，printf 才有输出。
*
*********************************************************************************************************
*/
#include "bsp.h"
#include "bsp_uart_fifo.h"

/*
*********************************************************************************************************
*   函 数 名: __io_putchar
*   功能说明: newlib 标准输出单字符钩子
*   返 回 值: 输出的字符
*********************************************************************************************************
*/
int __io_putchar(int ch)
{
    comSendChar(COM1, (uint8_t)ch);
    return ch;
}

/*
*********************************************************************************************************
*   函 数 名: __io_getchar
*   功能说明: newlib 标准输入单字符钩子。模板未启用串口接收解析，返回 -1。
*             如需 scanf，请在这里接 comGetChar(COM1, ...) 并做阻塞/超时处理。
*********************************************************************************************************
*/
int __io_getchar(void)
{
    return -1;
}
